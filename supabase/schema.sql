-- RBX BANGLADESH — SUPABASE ALL-IN-ONE MIGRATION
-- --------------------------------------------------------------------------
-- Run this entire file in the Supabase Dashboard → SQL Editor → New query.
-- It creates every table, enables Row Level Security with sensible policies,
-- creates the `rbx-media` storage bucket, and inserts demo seed data.
--
-- AUTH: Admin login uses Supabase Auth (email + password). After running this
-- script, go to Authentication → Users → "Add user" and create your admin
-- (e.g. admin@rbx.gg). The /admin portal is protected by middleware.
--
-- This file is safe to re-run: it truncates + reseeds the demo tables.
-- ==========================================================================

create extension if not exists "pgcrypto";

-- ------------------------------- Tables ---------------------------------- --
create table if not exists public.bladers (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  real_name text,
  role text not null default 'core',           -- captain | core | reserve
  playstyle text not null default 'balance',   -- attack | defense | stamina | balance
  experience text,
  avatar_url text,
  banner_url text,
  signature_combo text,
  launch_technique text,
  bio text,
  wins integer not null default 0,
  losses integer not null default 0,
  featured boolean not null default false,
  joined_at date,
  created_at timestamptz not null default now()
);

create table if not exists public.combos (
  id bigint generated by default as identity primary key,
  name text not null,
  blade text not null,
  ratchet text not null,
  bit text not null,
  archetype text not null default 'balance',
  blader_id bigint references public.bladers(id) on delete set null,
  description text,
  image_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.medals (
  id bigint generated by default as identity primary key,
  title text not null,
  tier text not null default 'gold',           -- gold | silver | bronze | special
  category text not null default 'regular',    -- regular | swiss | invitational
  event_name text not null,
  organizer text,
  venue text,
  awarded_on date,
  placement integer,
  blader_id bigint references public.bladers(id) on delete cascade,
  narrative text,
  featured boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.medal_photos (
  id bigint generated by default as identity primary key,
  medal_id bigint not null references public.medals(id) on delete cascade,
  url text not null,
  kind text not null default 'front',          -- front | back | certificate
  created_at timestamptz not null default now()
);

create table if not exists public.tournaments (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  date date,
  location text,
  organizer text,
  description text,
  poster_url text,
  status text not null default 'past',         -- past | upcoming
  format text default 'Swiss + Top Cut',
  created_at timestamptz not null default now()
);

create table if not exists public.tournament_results (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.tournaments(id) on delete cascade,
  blader_id bigint references public.bladers(id) on delete set null,
  placement integer not null,
  created_at timestamptz not null default now()
);

create table if not exists public.milestones (
  id bigint generated by default as identity primary key,
  blader_id bigint not null references public.bladers(id) on delete cascade,
  title text not null,
  happened_on date,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.gallery_items (
  id bigint generated by default as identity primary key,
  title text not null,
  image_url text not null,
  category text not null default 'battle',
  created_at timestamptz not null default now()
);

create table if not exists public.join_applications (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  city text,
  experience text,
  main_combo text,
  message text,
  status text not null default 'new',
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  subject text,
  message text not null,
  created_at timestamptz not null default now()
);

create index if not exists medals_blader_idx on public.medals(blader_id);
create index if not exists medals_tier_idx on public.medals(tier);

-- --------------------------- Aggregation view ---------------------------- --
create or replace view public.team_stats as
select
  (select count(*) from public.bladers)                         as total_bladers,
  (select count(*) from public.medals)                          as total_medals,
  (select count(*) from public.medals where tier = 'gold')      as gold,
  (select count(*) from public.medals where tier = 'silver')    as silver,
  (select count(*) from public.medals where tier = 'bronze')    as bronze,
  (select count(*) from public.tournament_results where placement = 1) as victories;

-- ------------------------- Row Level Security ---------------------------- --
alter table public.bladers            enable row level security;
alter table public.combos             enable row level security;
alter table public.medals             enable row level security;
alter table public.medal_photos       enable row level security;
alter table public.tournaments        enable row level security;
alter table public.tournament_results enable row level security;
alter table public.milestones         enable row level security;
alter table public.gallery_items      enable row level security;
alter table public.join_applications  enable row level security;
alter table public.contact_messages   enable row level security;

-- Public read on all catalog tables
do $$ declare t text; begin
  foreach t in array array['bladers','combos','medals','medal_photos','tournaments','tournament_results','milestones','gallery_items'] loop
    execute format('drop policy if exists "public read %1$s" on public.%1$s', t);
    execute format('create policy "public read %1$s" on public.%1$s for select using (true)', t);
    execute format('drop policy if exists "admin write %1$s" on public.%1$s', t);
    execute format('create policy "admin write %1$s" on public.%1$s for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

-- join_applications: anyone may submit; only authenticated (admin) may read/manage
drop policy if exists "public insert applications" on public.join_applications;
create policy "public insert applications" on public.join_applications for insert to anon, authenticated with check (true);
drop policy if exists "admin manage applications" on public.join_applications;
create policy "admin manage applications" on public.join_applications for all to authenticated using (true) with check (true);

-- contact_messages: anyone may submit; only admin may read/manage
drop policy if exists "public insert messages" on public.contact_messages;
create policy "public insert messages" on public.contact_messages for insert to anon, authenticated with check (true);
drop policy if exists "admin manage messages" on public.contact_messages;
create policy "admin manage messages" on public.contact_messages for all to authenticated using (true) with check (true);

-- ----------------------------- Storage ----------------------------------- --
insert into storage.buckets (id, name, public)
values ('rbx-media', 'rbx-media', true)
on conflict (id) do nothing;

drop policy if exists "rbx media public read" on storage.objects;
create policy "rbx media public read" on storage.objects for select using (bucket_id = 'rbx-media');
drop policy if exists "rbx media auth insert" on storage.objects;
create policy "rbx media auth insert" on storage.objects for insert to authenticated with check (bucket_id = 'rbx-media');
drop policy if exists "rbx media auth update" on storage.objects;
create policy "rbx media auth update" on storage.objects for update to authenticated using (bucket_id = 'rbx-media');
drop policy if exists "rbx media auth delete" on storage.objects;
create policy "rbx media auth delete" on storage.objects for delete to authenticated using (bucket_id = 'rbx-media');

